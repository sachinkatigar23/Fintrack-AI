import mongoose from "mongoose";
import { EXPENSE_CATEGORIES, PAYMENT_METHODS } from "../utils/constants.js";

export { EXPENSE_CATEGORIES, PAYMENT_METHODS };

const expenseSchema = new mongoose.Schema(
  {
    user: { type: mongoose.Schema.Types.ObjectId, ref: "User", required: true, index: true },
    title: { type: String, required: true, trim: true, maxlength: 100 },
    amount: { type: Number, required: true, min: 0.01 },
    category: { type: String, required: true, enum: EXPENSE_CATEGORIES },
    paymentMethod: { type: String, required: true, enum: PAYMENT_METHODS, default: "upi" },
    date: { type: Date, required: true, default: Date.now },
    notes: { type: String, trim: true, maxlength: 500, default: "" },
    receiptUrl: { type: String, default: "" },
    // true when the record was generated by a recurring rule or a paid bill
    isRecurring: { type: Boolean, default: false },
    // "user" = logged by the person (counts for the logging streak); "system" = created by the scheduler
    createdBy: { type: String, enum: ["user", "system"], default: "user" },
  },
  { timestamps: true }
);

expenseSchema.index({ user: 1, date: -1 });
expenseSchema.index({ user: 1, category: 1, date: -1 });

export default mongoose.model("Expense", expenseSchema);
